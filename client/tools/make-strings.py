"""Generates the .resx files and the C# accessor class from a strings table.

Usage: python make-strings.py      (no arguments, no extra packages; run from anywhere)

Each table is a UTF-8 text file with one string per line: key, English text and Russian text separated by TAB
characters. Lines starting with # and empty lines are skipped. "\\n" in a text becomes a line break.
For every table listed in TABLES this writes:
    <Name>.resx and <Name>.ru.resx next to the table (neutral = English, plus Russian), and
    the accessor class <Name>.g.cs with one static property per key. The class declares no accessibility; a
    hand-written partial part of it does, and provides Get(string name).
The generated files are committed; run this script after changing a table.
"""
import os
import sys
from xml.sax.saxutils import escape

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

# (table, namespace, class, accessor file)
TABLES = [
    ("src/Custos.Core/Resources/Messages.tsv", "Custos.Core", "Messages", "src/Custos.Core/Messages.g.cs"),
    ("src/Custos.Gui/Resources/Strings.tsv", "Custos.Gui", "Strings", "src/Custos.Gui/Strings.g.cs"),
    ("src/Custos.Desktop/Resources/DesktopStrings.tsv", "Custos.Desktop", "DesktopStrings", "src/Custos.Desktop/DesktopStrings.g.cs"),
]

RESX_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make-strings.py from {table}. Do not edit: change the table and run the script. -->
<root>
  <resheader name="resmimetype">
    <value>text/microsoft-resx</value>
  </resheader>
  <resheader name="version">
    <value>2.0</value>
  </resheader>
  <resheader name="reader">
    <value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
  <resheader name="writer">
    <value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
"""


def read_table(path):
    rows = []
    seen = set()
    with open(path, encoding="utf-8") as f:
        for number, line in enumerate(f, 1):
            line = line.rstrip("\n").rstrip("\r")
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 3:
                sys.exit(f"{path}:{number}: expected 3 columns separated by TAB, got {len(parts)}")
            key, en, ru = (p.strip() for p in parts)
            if not key.isidentifier():
                sys.exit(f"{path}:{number}: '{key}' is not a valid name")
            if key in seen:
                sys.exit(f"{path}:{number}: duplicate key '{key}'")
            if not en or not ru:
                sys.exit(f"{path}:{number}: '{key}' needs both texts")
            seen.add(key)
            rows.append((key, en.replace("\\n", "\n"), ru.replace("\\n", "\n")))
    return rows


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)


def write_resx(path, table, rows, column):
    parts = [RESX_HEADER.format(table=table)]
    for row in rows:
        parts.append(f'  <data name="{row[0]}" xml:space="preserve">\n    <value>{escape(row[column])}</value>\n  </data>\n')
    parts.append("</root>\n")
    write(path, "".join(parts))


def write_accessor(path, table, namespace, cls, rows):
    lines = [
        f"// <auto-generated>Generated by tools/make-strings.py from {table}. Do not edit.</auto-generated>",
        "#nullable enable",
        "",
        f"namespace {namespace};",
        "",
        f"static partial class {cls}",
        "{",
    ]
    for key, en, _ in rows:
        summary = en.split("\n")[0]
        if len(summary) > 110:
            summary = summary[:107] + "..."
        summary = escape(summary)
        lines.append(f"    /// <summary>{summary}</summary>")
        lines.append(f"    public static string {key} => Get(nameof({key}));")
        lines.append("")
    lines[-1] = "}"
    write(path, "\n".join(lines) + "\n")


def main():
    for table, namespace, cls, accessor in TABLES:
        table_path = os.path.join(ROOT, table)
        rows = read_table(table_path)
        base = os.path.splitext(table_path)[0]
        write_resx(base + ".resx", table, rows, 1)
        write_resx(base + ".ru.resx", table, rows, 2)
        write_accessor(os.path.join(ROOT, accessor), table, namespace, cls, rows)
        print(f"{table}: {len(rows)} strings")


if __name__ == "__main__":
    main()
