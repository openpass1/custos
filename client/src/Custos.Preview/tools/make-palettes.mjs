// Builds Palettes.g.cs: the colour schemes the trial window offers in «Настройки» → «Цвет», light and dark.
//
// The colours come from Google's Material Color Utilities (Apache License 2.0), the same algorithm that made the
// palette of the monitoring site (server/public/assets/app.css, scheme «tonal spot» of #2457c5).
//
//     npm install @material/material-color-utilities@0.3.0      (anywhere, once; 0.4 needs a bundler)
//     node tools/make-palettes.mjs path/to/node_modules
//
// Ok, warning and error colours are not here: they stay the same in every scheme (App.axaml).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const modules = process.argv[2];
if (!modules) {
  console.error('Usage: node tools/make-palettes.mjs path/to/node_modules');
  process.exit(1);
}

const m = await import(pathToFileURL(join(resolve(modules), '@material/material-color-utilities/index.js')).href);
const { Hct, argbFromHex, DynamicScheme, TonalPalette, SchemeTonalSpot, SchemeFidelity, SchemeMonochrome, MaterialDynamicColors: C } = m;

const hct = (hex) => Hct.fromInt(argbFromHex(hex));

// The site's scheme with grey surfaces: the blue of the site stays on buttons and selection, the background has no tint.
function neutralSurfaces(isDark) {
  const site = new SchemeTonalSpot(hct('#2457c5'), isDark, 0);
  return new DynamicScheme({
    sourceColorArgb: site.sourceColorArgb,
    variant: site.variant,
    contrastLevel: 0,
    isDark,
    primaryPalette: site.primaryPalette,
    secondaryPalette: site.secondaryPalette,
    tertiaryPalette: site.tertiaryPalette,
    neutralPalette: TonalPalette.fromHueAndChroma(site.sourceColorHct.hue, 0),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(site.sourceColorHct.hue, 2),
  });
}

const SCHEMES = [
  // As the site: a hint of violet in the surfaces, because the hue of #2457c5 is 271°.
  ['site', (dark) => new SchemeTonalSpot(hct('#2457c5'), dark, 0)],
  ['neutral', neutralSurfaces],
  // The default accent of Windows 11, kept close to itself («fidelity»): a clear blue, cool grey-blue surfaces.
  ['blue', (dark) => new SchemeFidelity(hct('#0067c0'), dark, 0)],
  ['teal', (dark) => new SchemeTonalSpot(hct('#006a6a'), dark, 0)],
  ['graphite', (dark) => new SchemeMonochrome(hct('#2457c5'), dark, 0)],
];

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'secondaryContainer', 'onSecondaryContainer',
  'surface', 'onSurface', 'onSurfaceVariant', 'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest', 'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface',
  'inversePrimary',
];

const hex = (argb) => '0x' + (argb >>> 0).toString(16).toUpperCase().padStart(8, '0');
const cap = (s) => s[0].toUpperCase() + s.slice(1);

let body = '';
for (const [id, make] of SCHEMES) {
  body += `        new("${id}",\n`;
  for (const dark of [false, true]) {
    const scheme = make(dark);
    const pairs = ROLES.map((role) => `["${cap(role)}"] = ${hex(C[role].getArgb(scheme))}`);
    body += `            new Dictionary<string, uint> { ${pairs.join(', ')} }${dark ? '),' : ','}\n`;
  }
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'Palettes.g.cs');
writeFileSync(out, `// <auto-generated>
// Made by tools/make-palettes.mjs with Material Color Utilities (Apache License 2.0). Do not edit by hand.
// </auto-generated>
namespace Custos.Preview;

internal static partial class Palettes
{
    private static readonly Scheme[] Schemes =
    [
${body}    ];
}
`);
console.log(`${SCHEMES.length} schemes -> ${out}`);
