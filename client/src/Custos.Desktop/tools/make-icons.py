#!/usr/bin/env python3
"""Builds IconData.g.cs, the icons of the new window, from Material Symbols Rounded (weight 400).

The icons are Google's Material Symbols (Apache License 2.0), the same set the monitoring site uses
(server/tools/make-icons.py). Only the paths of the icons listed below are copied into the program.

    npm install @material-symbols/svg-400        (anywhere, once)
    python3 tools/make-icons.py path/to/node_modules/@material-symbols/svg-400/rounded

An icon is used as <p:Icon Kind="sync"/>; Filled="True" takes the filled form where it is listed with "+".
"""
import re
import sys
from pathlib import Path

ICONS = [
    # Toolbar and menus
    'add', 'arrow_drop_down', 'arrow_drop_up', 'edit', 'content_copy', 'delete', 'toggle_off', 'toggle_on', 'play_arrow+',
    'stop+', 'pause', 'settings_backup_restore', 'view_sidebar+', 'settings', 'lock', 'upload_file', 'input', 'download',
    'brightness_auto', 'light_mode', 'dark_mode', 'check', 'close', 'arrow_upward', 'arrow_downward', 'folder_open',
    'filter_list', 'more_vert',
    # States
    'check_circle+', 'warning+', 'cancel+', 'sync', 'do_not_disturb_on+', 'radio_button_unchecked', 'schedule+',
    'pause_circle+', 'error+', 'info+', 'play_circle+', 'hourglass_top',
    # Tabs, status bar, empty states
    'receipt_long+', 'history', 'monitoring', 'cloud_done', 'cloud_off', 'cloud_sync', 'cloud', 'person', 'favorite+',
    'link_off', 'shield+', 'task_alt',
    # Task editor: pages, cards of sources, destinations and events, fields
    'description+', 'folder+', 'database+', 'hard_drive+', 'folder_zip+', 'layers+', 'bolt+', 'tune+', 'lan', 'dns', 'usb',
    'cloud_upload', 'terminal', 'stop_circle', 'lock_clock', 'label', 'speed', 'help', 'event_available', 'key',
    'power_settings_new', 'palette', 'visibility_off',
]

NUMBER = re.compile(r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')
TOKEN = re.compile(r'[MmZzLlHhVvCcSsQqTtAa]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')


def normalize(d: str) -> str:
    """The same path with every number set apart by a space, so any path parser reads it the same way."""
    if re.search(r'[Aa]', d):
        raise SystemExit('arcs are not expected in Material Symbols paths')
    return ' '.join(TOKEN.findall(d))


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1])
    lines = []
    for item in ICONS:
        name = item.rstrip('+')
        forms = [(name, name)] + ([(name + '+fill', name + '-fill')] if item.endswith('+') else [])
        for key, file in forms:
            svg = (src / (file + '.svg')).read_text(encoding='utf-8')
            paths = re.findall(r'<path d="([^"]+)"', svg)
            if not paths:
                raise SystemExit(f'no path in {file}.svg')
            lines.append(f'        ["{key}"] = "{normalize(" ".join(paths))}",')
    out = Path(__file__).resolve().parent.parent / 'IconData.g.cs'
    out.write_text('''// <auto-generated>
// Made by tools/make-icons.py from Material Symbols Rounded 400 (Apache License 2.0). Do not edit by hand.
// </auto-generated>
namespace Custos.Desktop;

internal static partial class IconData
{
    /// <summary>Path data in the 960 x 960 box of Material Symbols (y from -960 to 0).</summary>
    private static readonly Dictionary<string, string> Paths = new(StringComparer.Ordinal)
    {
''' + '\n'.join(lines) + '''
    };
}
''', encoding='utf-8', newline='\n')
    print(f'{len(lines)} icons -> {out}')


if __name__ == '__main__':
    main()
